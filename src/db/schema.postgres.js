/**
 * Postgres schema for Supabase, shared by two consumers:
 *   - `npm run migrate:pg`, to apply it by hand
 *   - the runtime guard in src/db/migrate.js, so a fresh database is never
 *     left without tables
 *
 * It must declare the same tables as src/db/migrations/001_init.sql (the
 * SQLite side); a test checks it. Every statement is idempotent, so applying
 * it twice is harmless.
 */
export const POSTGRES_SCHEMA_NAME = '001_init';

export const POSTGRES_SCHEMA = String.raw`-- Web Monitor schema for Supabase (Postgres).
-- Mirrors src/db/migrations/001_init.sql; timestamps stay TEXT (ISO-8601 UTC)
-- and booleans stay 0/1 SMALLINT so a single set of queries serves both dialects.

CREATE TABLE IF NOT EXISTS websites (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                TEXT     NOT NULL,
  url                 TEXT     NOT NULL UNIQUE,
  active              SMALLINT NOT NULL DEFAULT 1,
  check_interval      INTEGER  NOT NULL DEFAULT 60,
  detection_method    TEXT     NOT NULL DEFAULT 'auto',
  selector_config     TEXT     NOT NULL DEFAULT '{}',
  notes               TEXT,
  baseline_done       SMALLINT NOT NULL DEFAULT 0,
  last_checked_at     TEXT,
  last_success_at     TEXT,
  last_error          TEXT,
  last_error_at       TEXT,
  error_count         INTEGER  NOT NULL DEFAULT 0,
  consecutive_errors  INTEGER  NOT NULL DEFAULT 0,
  last_new_item_at    TEXT,
  last_new_item_title TEXT,
  created_at          TEXT     NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
  updated_at          TEXT     NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE INDEX IF NOT EXISTS idx_websites_active ON websites(active);

CREATE TABLE IF NOT EXISTS workers (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT     NOT NULL,
  email      TEXT     NOT NULL UNIQUE,
  active     SMALLINT NOT NULL DEFAULT 1,
  created_at TEXT     NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
  updated_at TEXT     NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE INDEX IF NOT EXISTS idx_workers_active ON workers(active);

CREATE TABLE IF NOT EXISTS posts (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  website_id    INTEGER NOT NULL REFERENCES websites(id) ON DELETE CASCADE,
  title         TEXT    NOT NULL,
  url           TEXT,
  published_at  TEXT,
  content_hash  TEXT    NOT NULL,
  excerpt       TEXT,
  first_seen_at TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
  notified_at   TEXT,
  UNIQUE (website_id, content_hash)
);
CREATE INDEX IF NOT EXISTS idx_posts_website_seen ON posts(website_id, first_seen_at DESC);
CREATE INDEX IF NOT EXISTS idx_posts_seen ON posts(first_seen_at DESC);

CREATE TABLE IF NOT EXISTS check_logs (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  website_id    INTEGER  NOT NULL REFERENCES websites(id) ON DELETE CASCADE,
  checked_at    TEXT     NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
  success       SMALLINT NOT NULL,
  new_items     INTEGER  NOT NULL DEFAULT 0,
  items_found   INTEGER  NOT NULL DEFAULT 0,
  method        TEXT,
  duration_ms   INTEGER,
  error_message TEXT
);
CREATE INDEX IF NOT EXISTS idx_check_logs_website ON check_logs(website_id, checked_at DESC);
CREATE INDEX IF NOT EXISTS idx_check_logs_checked ON check_logs(checked_at DESC);

CREATE TABLE IF NOT EXISTS settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);

CREATE TABLE IF NOT EXISTS crawler_state (
  id                   INTEGER PRIMARY KEY CHECK (id = 1),
  status               TEXT NOT NULL DEFAULT 'stopped',
  last_run_at          TEXT,
  last_run_duration_ms INTEGER,
  next_run_at          TEXT,
  last_heartbeat_at    TEXT,
  pid                  BIGINT,
  updated_at           TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
INSERT INTO crawler_state (id, status) VALUES (1, 'stopped') ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS sessions (
  sid        TEXT PRIMARY KEY,
  expires_at BIGINT NOT NULL,
  data       TEXT   NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);

INSERT INTO settings (key, value) VALUES
  ('default_check_interval', '600'),
  ('scheduler_tick', '60'),
  ('crawler_concurrency', '8'),
  ('notify_on_first_check', 'false'),
  ('max_items_per_email', '20'),
  ('crawler_enabled', 'true'),
  ('log_retention_days', '30')
ON CONFLICT (key) DO NOTHING;
`;
